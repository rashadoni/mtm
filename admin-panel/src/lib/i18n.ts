/**
 * Get translation for a key.
 * Usage: t('nav.dashboard') -> 'İdarə Paneli'
 */
export function t(key: string, locale?: Locale): string {
  const currentLocale = locale || useI18nStore.getState().locale;
  return translations[currentLocale]?.[key] || translations['az']?.[key] || key;
}

/**
 * Hook to use translations reactively.
 */
export function useTranslation() {
  const locale = useI18nStore((s) => s.locale);
  const setLocale = useI18nStore((s) => s.setLocale);

  const translate = (key: string): string => {
    return translations[locale]?.[key] || translations['az']?.[key] || key;
  };

  return { t: translate, locale, setLocale };
}

